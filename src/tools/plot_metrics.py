"""Render thesis-ready figures from a training run's metrics.json.

Addresses marker feedback on the Phase 1 literature review: *"Good presentation,
but missed opportunity to include graphs"*. Figures are generated from measured
data (the per-epoch history written by train.py), never drawn by hand.

Produces:
  <out>/training_curves.(pdf|png)  — loss, BLEU-4 and WER vs epoch, best epoch marked
  <out>/metrics_summary.tex        — a LaTeX table of the headline numbers

Usage
-----
    python tools/plot_metrics.py --metrics runs/baseline/metrics.json --out figures/

Use the PDF in LaTeX (vector, scales cleanly):
    \\includegraphics[width=\\linewidth]{figures/training_curves.pdf}
"""
from __future__ import annotations

import argparse
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def plot(metrics_path: str, out_dir: str, dpi: int = 200) -> None:
    with open(metrics_path) as f:
        m = json.load(f)
    hist = m.get("history", [])
    if not hist:
        raise SystemExit("no 'history' in metrics.json — nothing to plot")
    os.makedirs(out_dir, exist_ok=True)

    ep = [h["epoch"] for h in hist]
    loss = [h["loss"] for h in hist]
    bleu = [h["bleu4"] for h in hist]
    wer = [h["wer"] for h in hist]
    best_ep = (m.get("best") or {}).get("epoch")

    fig, axes = plt.subplots(1, 3, figsize=(12, 3.4))
    panels = [
        (axes[0], loss, "Training loss", "Loss", "#1f77b4", False),
        (axes[1], bleu, "Validation BLEU-4", "BLEU-4", "#2ca02c", True),
        (axes[2], wer, "Validation WER", "WER", "#d62728", False),
    ]
    for ax, y, title, ylab, colour, mark_best in panels:
        ax.plot(ep, y, marker="o", ms=3, lw=1.4, color=colour)
        ax.set_title(title, fontsize=11)
        ax.set_xlabel("Epoch"); ax.set_ylabel(ylab)
        ax.grid(alpha=0.3, ls=":")
        if mark_best and best_ep:
            by = y[ep.index(best_ep)]
            ax.axvline(best_ep, color="grey", ls="--", lw=0.9)
            ax.annotate(f"best: {by:.2f}\n(ep {best_ep})", xy=(best_ep, by),
                        xytext=(6, -6), textcoords="offset points", fontsize=8)
    # WER = 1.0 reference: above it the hypothesis is worse than emitting nothing
    axes[2].axhline(1.0, color="grey", ls=":", lw=0.9)

    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(out_dir, f"training_curves.{ext}"), dpi=dpi, bbox_inches="tight")
    plt.close(fig)

    # LaTeX summary table — headline numbers, with the BLEU signature recorded
    best = m.get("best", {}) or {}
    test = m.get("test") or {}
    sig = m.get("bleu_signature", "n/a")
    rows = [("Validation (model selection)", best.get("bleu4"), best.get("wer"))]
    if test:
        rows.append(("Test (reported)", test.get("bleu4"), test.get("wer")))
    body = "\n".join(
        f"    {n} & {b:.2f} & {w:.3f} \\\\" for n, b, w in rows
        if isinstance(b, (int, float)) and isinstance(w, (int, float)))
    tex = (
        "% generated by tools/plot_metrics.py -- do not edit by hand\n"
        "\\begin{table}[t]\n  \\centering\n"
        "  \\caption{Gloss-free pose baseline on Auslan-Daily. "
        f"BLEU computed as: \\texttt{{{sig}}}.}}\n"
        "  \\label{tab:phase2-baseline}\n"
        "  \\begin{tabular}{lrr}\n    \\toprule\n"
        "    Split & BLEU-4 & WER \\\\\n    \\midrule\n"
        f"{body}\n"
        "    \\bottomrule\n  \\end{tabular}\n\\end{table}\n"
    )
    with open(os.path.join(out_dir, "metrics_summary.tex"), "w") as f:
        f.write(tex)

    print(f"[write] {out_dir}/training_curves.pdf (+ .png)")
    print(f"[write] {out_dir}/metrics_summary.tex")
    print(f"[info] epochs={len(ep)} best_epoch={best_ep} bleu_signature={sig}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--metrics", required=True)
    ap.add_argument("--out", default="figures")
    ap.add_argument("--dpi", type=int, default=200)
    a = ap.parse_args()
    plot(a.metrics, a.out, a.dpi)
